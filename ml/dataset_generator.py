"""
Rakshak-AI Machine Learning Module: Synthetic IMU Telemetry Generator
---------------------------------------------------------------------
Generates realistic 3-axis accelerometer and gyroscope time-series windows (50 samples @ 50Hz = 1.0s window)
for 3 distinct vehicle/device motion classes:
  0: 'normal'  - Everyday vehicle cruising, braking, phone handling, and mild road vibrations.
  1: 'pothole' - High-frequency, low-amplitude oscillatory bursts (1.5G - 4.0G) per Phase 9 specifications.
  2: 'crash'   - Extreme deceleration impact spikes (6.5G - 14.0G) with high angular shock and sudden stop.

DATASET PROVENANCE NOTE:
All samples generated by this script are SYNTHETIC, mathematically simulated from kinematic equations
and stochastic noise models. Real-world vehicle crash telemetry is not realistically available or publicly
benchmarked in hackathon scope. The model trained on this data is explicitly validated against synthetic
test distributions.
"""

import numpy as np
from typing import Tuple, List

# Window parameters
WINDOW_SIZE = 50   # 50 samples @ 50 Hz = 1.0 second observation window
CHANNELS = 2      # Channel 0: net acceleration deviation in Gs (|total_accel - 1G|)
                  # Channel 1: gyroscope angular velocity magnitude in rad/s

CLASSES = ['normal', 'pothole', 'crash']
CLASS_TO_IDX = {name: idx for idx, name in enumerate(CLASSES)}
IDX_TO_CLASS = {idx: name for idx, name in enumerate(CLASSES)}


def generate_normal_sample(rng: np.random.Generator) -> np.ndarray:
    """
    Generates a 50x2 window simulating normal driving and phone movement.
    - Low acceleration deviation: 0.02G to 0.7G
    - Low gyroscope angular rate: 0.05 to 1.0 rad/s
    - Colored noise simulating engine and road texture
    """
    t = np.linspace(0, 1.0, WINDOW_SIZE)
    
    # Baseline road vibration (Pink-like colored noise using cumulative sum of Gaussian)
    white_noise = rng.normal(0, 0.08, WINDOW_SIZE)
    road_vibe = np.convolve(white_noise, np.ones(3)/3, mode='same')
    
    # Mild vehicle maneuvering (gentle turn or smooth brake: low frequency sine)
    maneuver_freq = rng.uniform(0.5, 1.5)
    maneuver_amp = rng.uniform(0.05, 0.4)
    maneuver = maneuver_amp * np.sin(2 * np.pi * maneuver_freq * t + rng.uniform(0, 2*np.pi))
    
    # Net G deviation (always positive magnitude in Gs)
    accel = np.abs(road_vibe + maneuver + rng.normal(0.05, 0.02, WINDOW_SIZE))
    accel = np.clip(accel, 0.0, 1.2)  # Normal driving rarely exceeds 1.2G net
    
    # Gyroscope magnitude (rad/s)
    gyro_base = rng.uniform(0.05, 0.25)
    gyro_noise = np.abs(rng.normal(0, 0.1, WINDOW_SIZE))
    gyro = np.clip(gyro_base + gyro_noise + 0.3 * np.abs(maneuver), 0.0, 1.5)
    
    sample = np.stack([accel, gyro], axis=-1)  # (50, 2)
    return sample.astype(np.float32)


def generate_pothole_sample(rng: np.random.Generator) -> np.ndarray:
    """
    Generates a 50x2 window simulating a pothole or speed-bump encounter.
    - Replicates Phase 9 Kinematic Filter specs:
      * Peak G in [1.5G, 4.0G]
      * High-frequency oscillatory burst (3+ sign reversals within ~300ms)
      * Moderate angular shock (0.8 - 2.8 rad/s)
      * Decays back to normal road vibration (does NOT drop speed to zero)
    """
    t = np.linspace(0, 1.0, WINDOW_SIZE)
    sample = generate_normal_sample(rng)  # start with baseline normal driving
    
    # Burst location: somewhere in the middle of the 1-second window
    burst_center_idx = rng.integers(15, 35)
    burst_duration_samples = rng.integers(10, 18)  # ~200ms - 350ms
    
    # High-frequency damped sinusoidal oscillation (10Hz - 25Hz road shock)
    osc_freq = rng.uniform(12.0, 24.0)
    peak_g = rng.uniform(1.6, 3.9)  # strictly within pothole range 1.5G - 4.0G
    
    for i in range(WINDOW_SIZE):
        dt = (i - burst_center_idx) / 50.0  # seconds from burst center
        if abs(dt) < 0.25:  # within 250ms of impact
            decay = np.exp(-abs(dt) * 12.0)  # rapid mechanical shock absorption decay
            osc = np.sin(2 * np.pi * osc_freq * dt)
            shock_g = peak_g * decay * abs(osc)
            sample[i, 0] = max(sample[i, 0], shock_g)
            
            # Gyro shock: rotational jerk from suspension deflection
            gyro_shock = rng.uniform(0.8, 2.5) * decay
            sample[i, 1] = max(sample[i, 1], gyro_shock)
            
    return sample.astype(np.float32)


def generate_crash_sample(rng: np.random.Generator) -> np.ndarray:
    """
    Generates a 50x2 window simulating a severe vehicle collision.
    - Replicates Phase 3 & Master Doc Crash Specs:
      * Deceleration spike >= 6.5G (typically 6.8G to 13.5G)
      * High rotational shock from angular collision impulse (3.5 to 9.5 rad/s)
      * Rapid collapse toward zero kinetic vibration post-impact (vehicle halted)
    """
    t = np.linspace(0, 1.0, WINDOW_SIZE)
    sample = generate_normal_sample(rng)
    
    # Impact timing: occurs between sample 15 and 30
    impact_idx = rng.integers(15, 30)
    peak_g = rng.uniform(6.6, 13.5)  # Severe crash deceleration >= 6.5G
    gyro_shock_peak = rng.uniform(3.5, 9.0)  # Severe rollover / spin torque
    
    # Impulse duration: ~100ms - 200ms (5 to 10 samples)
    impulse_width = rng.integers(4, 9)
    
    for i in range(WINDOW_SIZE):
        if i < impact_idx:
            # Pre-impact: normal vehicle driving
            continue
        elif i <= impact_idx + impulse_width:
            # Impact phase: massive deceleration spike with asymmetric rise/fall
            progress = (i - impact_idx) / impulse_width
            spike_shape = np.sin(np.pi * progress) ** 1.5
            sample[i, 0] = peak_g * spike_shape + rng.normal(0, 0.3)
            sample[i, 1] = gyro_shock_peak * spike_shape + rng.normal(0, 0.4)
        else:
            # Post-impact phase: vehicle has crashed and come to a sudden halt
            # Residual vibration decays rapidly to near stillness (vehicle stopped)
            halt_decay = np.exp(-(i - (impact_idx + impulse_width)) * 0.4)
            sample[i, 0] = 0.05 * halt_decay + rng.normal(0, 0.01)
            sample[i, 1] = 0.02 * halt_decay + rng.normal(0, 0.005)
            
    return np.clip(sample, 0.0, 20.0).astype(np.float32)


def generate_synthetic_dataset(
    n_per_class: int = 2000,
    seed: int = 42
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Generates a balanced dataset of synthetic IMU windows across all 3 classes.
    Returns:
        X: (N, 50, 2) float32 array
        y: (N,) int32 array (0=normal, 1=pothole, 2=crash)
    """
    rng = np.random.default_rng(seed)
    
    X_list: List[np.ndarray] = []
    y_list: List[int] = []
    
    # Generate normal driving windows
    for _ in range(n_per_class):
        X_list.append(generate_normal_sample(rng))
        y_list.append(CLASS_TO_IDX['normal'])
        
    # Generate pothole/speed-bump windows
    for _ in range(n_per_class):
        X_list.append(generate_pothole_sample(rng))
        y_list.append(CLASS_TO_IDX['pothole'])
        
    # Generate crash impact windows
    for _ in range(n_per_class):
        X_list.append(generate_crash_sample(rng))
        y_list.append(CLASS_TO_IDX['crash'])
        
    X = np.stack(X_list, axis=0)
    y = np.array(y_list, dtype=np.int32)
    
    # Shuffle dataset
    perm = rng.permutation(len(y))
    return X[perm], y[perm]


